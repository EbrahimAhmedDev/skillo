#!/usr/bin/env node
/* Writes a per-user desktop launcher for Skillo (Linux):
 *   ~/.local/bin/skillo       wrapper that starts the built app
 *   ~/.local/share/applications/skillo.desktop
 *   ~/.local/share/icons/skillo.png
 * Usage: npm run desktop
 *
 * GNOME/.desktop launches are run by systemd with a minimal environment
 * (no nvm, no `$HOME/.cargo`…), so the wrapper must NOT rely on the npm
 * shim `node_modules/.bin/electron` (that one needs `node` on PATH).
 * Instead we exec the real electron binary directly and prepend the node
 * bin directory to PATH so the app's `npx skills` calls still work.
 */

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const appDir = path.resolve(__dirname, "..");

// where node lives right now (works with nvm/fnm/system installs alike)
const nodeBin = path.dirname(process.execPath);

// the real electron executable, not the .bin shim
const electronBin = path.join(appDir, "node_modules", "electron", "dist", "electron");

if (!fs.existsSync(electronBin)) {
  console.error(`electron binary not found at ${electronBin} — run npm install first`);
  process.exit(1);
}

const localBin = path.join(os.homedir(), ".local", "bin");
const appsDir = path.join(os.homedir(), ".local", "share", "applications");
const iconSrc = path.join(appDir, "assets", "icons", "512x512.png");
const iconDst = path.join(os.homedir(), ".local", "share", "icons", "skillo.png");

for (const dir of [localBin, appsDir, path.dirname(iconDst)]) {
  fs.mkdirSync(dir, { recursive: true });
}

const wrapper = path.join(localBin, "skillo");
fs.writeFileSync(
  wrapper,
  [
    "#!/usr/bin/env bash",
    "# generated by Skillo's npm run desktop — safe to regenerate",
    `export PATH="${nodeBin}:$PATH"`,
    `exec "${electronBin}" "${appDir}" "$@"`,
    "",
  ].join("\n"),
  { mode: 0o755 },
);
fs.copyFileSync(iconSrc, iconDst);

const desktop = path.join(appsDir, "skillo.desktop");
fs.writeFileSync(
  desktop,
  [
    "[Desktop Entry]",
    "Type=Application",
    "Version=1.0",
    "Name=Skillo",
    "Comment=Skills manager for your AI agents (npx skills)",
    `Exec=${wrapper}`,
    `Icon=${iconDst}`,
    "Categories=Development;Utility;",
    "Terminal=false",
    "StartupWMClass=Skillo",
    "",
  ].join("\n"),
);

console.log(`desktop launcher written:\n  ${wrapper}\n  ${desktop}\n  ${iconDst}`);
console.log(`wrapper uses electron binary directly (node bin: ${nodeBin})`);
